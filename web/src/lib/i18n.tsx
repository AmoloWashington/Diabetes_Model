const DICTS: Record<Lang, Partial<Record<Key, string>>> = { en: EN, sw: SW };

/** Routes whose page content is translated; other pages show the "English only" note in Swahili. */
export const TRANSLATED_ROUTES = ["/physiology/cgm", "/assistant", "/feedback"];

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: Key, vars?: Record<string, string | number>) => string }>({
  lang: "en", setLang: () => {}, t: (k) => EN[k],
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem("glucolab-lang");
      if (saved === "en" || saved === "sw") return saved;
    } catch { /* storage unavailable */ }
    return "en";
  });
  useEffect(() => {
    document.documentElement.lang = lang;
    try { localStorage.setItem("glucolab-lang", lang); } catch { /* ignore */ }
  }, [lang]);
  const value = useMemo(() => ({
    lang, setLang,
    t: (k: Key, vars?: Record<string, string | number>) => {
      let s: string = DICTS[lang][k] ?? EN[k];
      if (vars) for (const [name, v] of Object.entries(vars)) s = s.replaceAll(`{${name}}`, String(v));
      return s;
    },
  }), [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
