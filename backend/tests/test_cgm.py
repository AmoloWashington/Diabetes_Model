import numpy as np
import pytest
from fastapi.testclient import TestClient

from app.main import app
from app.physiology import cgm

client = TestClient(app)


def _band(r, key):
    return next(b["pct"] for b in r["bands"] if b["key"] == key)


def test_gmi_formula_bergenstal_2018():
    # GMI (%) = 3.31 + 0.02392 x mean glucose (mg/dl)
    assert cgm.gmi_percent(154.0) == pytest.approx(3.31 + 0.02392 * 154.0)
    assert cgm.gmi_percent(100.0) == pytest.approx(5.702)


def test_band_boundaries_follow_consensus():
    # one reading per boundary case, 5 min apart
    g = np.array([53.9, 54.0, 69.9, 70.0, 180.0, 180.5, 250.0, 250.5, 100.0, 100.0])
    r = cgm.analyze(np.arange(g.size) * 5.0, g, "mg/dl")
    assert _band(r, "very_low") == pytest.approx(10.0)  # 53.9
    assert _band(r, "low") == pytest.approx(20.0)  # 54.0, 69.9
    assert _band(r, "in_range") == pytest.approx(40.0)  # 70, 180, 100, 100
    assert _band(r, "high") == pytest.approx(20.0)  # 180.5, 250
    assert _band(r, "very_high") == pytest.approx(10.0)  # 250.5
    assert sum(b["pct"] for b in r["bands"]) == pytest.approx(100.0)
    assert r["below_70_pct"] == pytest.approx(30.0)
    assert r["above_180_pct"] == pytest.approx(30.0)


def test_mean_sd_cv_and_targets():
    g = np.array([100.0, 120.0] * 10)
    r = cgm.analyze(np.arange(g.size) * 5.0, g, "mg/dl")
    assert r["mean_mg_dl"] == pytest.approx(110.0)
    assert r["cv_pct"] == pytest.approx(100 * np.std(g, ddof=1) / 110.0)
    tir = next(t for t in r["targets"] if t["metric"] == "in_range")
    assert tir["met"] is True


def test_mmol_detected_and_converted():
    g = np.full(20, 7.0)  # mmol/l
    r = cgm.analyze(np.arange(20) * 5.0, g)
    assert r["unit_detected"] == "mmol/l"
    assert r["mean_mg_dl"] == pytest.approx(7.0 * 18.016)


def test_out_of_range_values_rejected():
    with pytest.raises(ValueError):
        cgm.analyze(np.arange(20) * 5.0, np.full(20, 900.0), "mg/dl")


def test_agp_bins_use_time_of_day():
    t = np.arange(0, 2 * 1440, 5.0)  # two days, start at midnight
    g = np.where((t % 1440) < 720, 100.0, 200.0)  # mornings 100, afternoons 200
    r = cgm.analyze(t, g, "mg/dl", start_minute_of_day=0.0)
    assert r["agp"][0]["p50"] == pytest.approx(100.0)
    assert r["agp"][30]["p50"] == pytest.approx(200.0)  # bin starting 15:00


def test_parse_generic_csv_and_skip_text_values():
    rows = ["timestamp,glucose_mg_dl"] + [f"2026-01-01T00:{m:02d}:00,{100 + m}" for m in range(0, 60, 5)]
    rows.insert(3, "2026-01-01T00:07:00,Low")
    t, g, meta = cgm.parse_csv("\n".join(rows))
    assert g.size == 12 and meta["skipped_non_numeric"] == 1
    assert t[1] == pytest.approx(5.0)
    assert meta["start_minute_of_day"] == pytest.approx(0.0)


def test_parse_csv_with_metadata_line_above_header():
    lines = ["Glucose Data,Generated on,2026-01-02,Generated by,User",
             "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL"]
    lines += [f"Sensor,ABC,2026-01-01 08:{m:02d},0,{110 + m},"for m in range(0, 60, 15)] * 3
    t, g, meta = cgm.parse_csv("\n".join(lines))
    assert meta["glucose_column"] == "Historic Glucose mg/dL"
    assert meta["time_column"] == "Device Timestamp"
    assert meta["start_minute_of_day"] == pytest.approx(8 * 60)


def test_synthetic_sample_is_continuous_and_labelled():
    t, g = cgm.synthetic_sample("type2", days=3)
    assert np.all(np.diff(t) == 5.0)  # continuous across midnights
    assert t.size == 3 * 288


def test_api_sample_and_analyze():
    r = client.get("/api/cgm/sample", params={"phenotype": "normal", "days": 3})
    assert r.status_code == 200
    body = r.json()
    assert body["source"]["synthetic"] is True and body["days"] == pytest.approx(3.0)
    pts = [{"minute": 5.0 * i, "g": 120.0} for i in range(30)]
    r = client.post("/api/cgm/analyze", json={"points": pts, "unit": "mg/dl"})
    assert r.status_code == 200 and r.json()["mean_mg_dl"] == pytest.approx(120.0)
    assert client.post("/api/cgm/analyze", json={"unit": "mg/dl"}).status_code == 422
    assert client.post("/api/cgm/analyze", json={"csv": "nothing useful"}).status_code == 422
